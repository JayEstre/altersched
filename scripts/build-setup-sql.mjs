// Regenerates database/AlterSched_SETUP_ALL_IN_ONE.sql from the individual migrations.
// Usage: node scripts/build-setup-sql.mjs
import { readFileSync, writeFileSync } from 'node:fs'

const MIGRATIONS = [
  'AlterSched_Database_V2',
  'AlterSched_Auth_Fix_All',
  'AlterSched_BSIT_Panel_Batch1',
  'AlterSched_Professional_V2',
  'AlterSched_Claim_Workflow',
  'AlterSched_Change_Request_Policies',
  'AlterSched_Admin_Write_Policies',
  'AlterSched_Final_RLS',
  'AlterSched_V6_Fixes',
  'AlterSched_V7_Assignments',
  'AlterSched_V8_Scheduling_Settings',
]

const header = `-- ============================================================================
-- AlterSched - COMPLETE DATABASE SETUP (all migrations, in order)
-- Paste into Supabase > SQL Editor on a NEW project and click Run.
-- Then run AlterSched_Seed_Base.sql (edit school names first).
-- Generated by scripts/build-setup-sql.mjs - edit the individual files, not this one.
-- ============================================================================
`
const parts = MIGRATIONS.map((name) => {
  const sql = readFileSync(new URL(`../database/${name}.sql`, import.meta.url), 'utf8')
  return `\n\n-- ${'#'.repeat(76)}\n-- ## ${name}.sql\n-- ${'#'.repeat(76)}\n${sql}`
})
writeFileSync(
  new URL('../database/AlterSched_SETUP_ALL_IN_ONE.sql', import.meta.url),
  header + parts.join('')
)
console.log(`Wrote AlterSched_SETUP_ALL_IN_ONE.sql from ${MIGRATIONS.length} migrations`)
